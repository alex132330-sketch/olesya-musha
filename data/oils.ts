export function getOilBySlug(slug: string): Oil | undefined {
  return oils.find((o) => o.slug === slug);
}

export function getSimilarOils(oil: Oil, limit = 3): Oil[] {
  return oils
    .filter((o) => o.id !== oil.id && o.categories.some((c) => oil.categories.includes(c)))
    .slice(0, limit);
}
